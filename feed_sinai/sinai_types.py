    # type: ignore
    def convert(self, cls: type[SiblingModel], **updated_data: Any) -> SiblingModel:
        data = self.model_dump() | updated_data
        return cls(**data)

    def deep_get(self, *names: str) -> set[Any]:
        result = set()

        for name in names:
            value = getattr(self, name, [])
            if isinstance(value, List):
                result.update(value)
            elif value:
                # Don't add if value == None
                result.add(value)

        for field_name in self.__class__.model_fields:
            field_value = getattr(self, field_name, [])
            if isinstance(field_value, List):
                for obj in field_value:
                    if hasattr(obj, 'deep_get'):
                        result.update(obj.deep_get(*names))
            else:
                if hasattr(field_value, 'deep_get'):
                    result.update(field_value.deep_get(*names))

        return result


